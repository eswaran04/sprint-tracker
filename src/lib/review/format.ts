import { findReview, REVIEW_END, REVIEW_START, stripReview } from "./blocks";
import type { EdgeCase, Review } from "./schema";

const VERDICT: Record<Review["complexity"]["verdict"], string> = {
  optimal: "✅ Optimal",
  suboptimal: "⚠️ Can be improved",
  unknown: "❔ Optimal not determined",
};
const SEVERITY: Record<EdgeCase["severity"], string> = { bug: "🐞 **Bug**", risk: "⚠️ **Risk**", note: "💡 **Note**" };

/** Keeps model text from breaking the table / injecting markers. */
const cell = (s: string) => s.replace(/\|/g, "\\|").replace(/\n+/g, " ").replace(/<!--|-->/g, "").trim() || "—";
const inline = (s: string) => s.replace(/\n+/g, " ").replace(/<!--|-->/g, "").trim();

function where(e: EdgeCase, multiBlock: boolean) {
  if (e.line == null) return "";
  return multiBlock && e.block != null ? `block ${e.block}, line ${e.line}: ` : `Line ${e.line}: `;
}

export function renderReview(review: Review, ai: boolean, date = new Date()) {
  const { complexity: c } = review;
  const multiBlock = new Set(review.edge_cases.map((e) => e.block).filter((b) => b != null)).size > 1;
  const lines = [
    REVIEW_START,
    "---",
    "",
    "## 🤖 AI Review",
    "",
    `> ${inline(review.summary)}`,
    "",
    "### Complexity Check",
    "",
    "| | Yours | Optimal |",
    "|---|---|---|",
    `| Time | \`${cell(c.time)}\` | \`${cell(c.optimal_time)}\` |`,
    `| Space | \`${cell(c.space)}\` | \`${cell(c.optimal_space)}\` |`,
    "",
    `**${VERDICT[c.verdict]}**${c.explanation ? `: ${inline(c.explanation)}` : ""}`,
    "",
    "### Edge-Case Spotter",
    "",
    ...(review.edge_cases.length
      ? review.edge_cases.map((e) => `- ${SEVERITY[e.severity]}: ${where(e, multiBlock)}${inline(e.message)}`)
      : ["- No issues spotted."]),
    "",
    "### Pattern Tags",
    "",
    review.suggested_tags.length
      ? `Consider tagging: ${review.suggested_tags.map((t) => `\`${inline(t).replace(/`/g, "")}\``).join(" ")}`
      : "Your tags already cover the patterns used.",
    "",
    `*${ai ? "Generated by AI" : "Built-in analyzer (AI unavailable)"} · ${date.toISOString().slice(0, 10)}. Double-check before relying on it.*`,
    REVIEW_END,
  ];
  return lines.join("\n");
}

/** Replaces an existing review block, or appends one. Re-running never stacks duplicates. */
export function upsertReview(notes: string, block: string) {
  const found = findReview(notes);
  if (found) {
    const before = notes.slice(0, found.start).trimEnd();
    // Drop any further stray reviews so a hand-edited note converges to exactly one block.
    const after = stripReview(notes.slice(found.end));
    return [before, block, after].filter(Boolean).join("\n\n") + "\n";
  }
  const base = notes.trimEnd();
  return (base ? `${base}\n\n` : "") + block + "\n";
}
