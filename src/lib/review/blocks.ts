/** Parsing helpers shared by the prompt builder, the heuristic analyzer and the formatter. */

export const REVIEW_START = "<!-- ai-review:start -->";
export const REVIEW_END = "<!-- ai-review:end -->";

const REVIEW_HEADING = "## 🤖 AI Review";
const FOOTER_RE = /^\*(?:Generated by AI|Built-in analyzer)[^\n]*$/m;
const MARKER_RE = /<!-- ai-review:(?:start|end) -->\n?/g;

/**
 * Locates a previously inserted review, tolerating a hand-edited block where one marker was deleted:
 * - start marker without end → up to the review footer line (or just the marker);
 * - end marker without start → back to the "## 🤖 AI Review" heading (and its preceding `---`).
 */
export function findReview(notes: string): { start: number; end: number } | null {
  const s = notes.indexOf(REVIEW_START);
  if (s !== -1) {
    const e = notes.indexOf(REVIEW_END, s);
    if (e !== -1) return { start: s, end: e + REVIEW_END.length };
    const footer = FOOTER_RE.exec(notes.slice(s));
    return { start: s, end: footer ? s + footer.index + footer[0].length : s + REVIEW_START.length };
  }
  const e = notes.indexOf(REVIEW_END);
  if (e === -1) return null;
  const h = notes.lastIndexOf(REVIEW_HEADING, e);
  if (h === -1) return { start: e, end: e + REVIEW_END.length };
  const rule = /(?:^|\n)---[ \t]*\n\s*$/.exec(notes.slice(0, h));
  return { start: rule ? rule.index : h, end: e + REVIEW_END.length };
}

export interface CodeBlock {
  /** 1-based, in order of appearance. */
  index: number;
  lang: string;
  lines: string[];
}

/** Notes without any previously inserted review block (so a re-run doesn't review the review). */
export function stripReview(notes: string) {
  let out = notes;
  for (let r = findReview(out); r; r = findReview(out)) out = `${out.slice(0, r.start).trimEnd()}\n\n${out.slice(r.end).trimStart()}`;
  return out.trim();
}

/** Removes only the invisible markers, for rendering (react-markdown would show HTML comments as text). */
export function stripMarkers(notes: string) {
  return notes.replace(MARKER_RE, "");
}

const FENCE_RE = /^(`{3,}|~{3,})[ \t]*([\w+#.-]*)[^\n]*\n([\s\S]*?)^\1[ \t]*$/gm;

export function extractBlocks(notes: string): CodeBlock[] {
  const out: CodeBlock[] = [];
  for (const m of notes.matchAll(FENCE_RE)) {
    const code = m[3].replace(/\n$/, "");
    if (!code.trim()) continue;
    out.push({ index: out.length + 1, lang: m[2].toLowerCase(), lines: code.split("\n") });
  }
  return out;
}

/** The note text outside code fences (approach, stated complexity...). */
export function proseOf(notes: string) {
  return notes.replace(FENCE_RE, "").replace(/\n{3,}/g, "\n\n").trim();
}

/** What the user wrote after "Time:" / "Space:", e.g. "- Time: O(n log n)". Empty template values are ignored. */
export function statedComplexity(notes: string): { time: string | null; space: string | null } {
  const grab = (word: string) => {
    const m = new RegExp(`\\b${word}\\b[^:\\n]*[:=\\-]\\s*[\`$]*(O\\([^\\n\`$]*\\))`, "i").exec(notes);
    const v = m?.[1].trim() ?? null;
    return v && v.replace(/\s/g, "") !== "O()" ? v : null;
  };
  return { time: grab("time"), space: grab("space") };
}

/** Loose canonical form for comparing complexities: "O(n log n)" == "O(N·logN)". */
export function normComplexity(s: string) {
  return s
    .toLowerCase()
    .replace(/[\s·*`$\\]/g, "")
    .replace(/\^\{?(\w+)\}?/g, "^$1")
    .replace(/²/g, "^2")
    .replace(/log\(n\)/g, "logn")
    .replace(/n\^1(?!\d)/g, "n");
}
